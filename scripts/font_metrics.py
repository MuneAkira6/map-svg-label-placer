#!/usr/bin/env python3
"""Extract advance widths from the fonts Wikimedia Commons renders SVGs with, into src/fonts/metrics.json.

Commons renders SVG with librsvg 2.60 on Debian trixie (since 2026-08-17). The font files come from these
Debian packages (https://deb.debian.org/debian/pool/main/f/<source>/<package>_<version>_all.deb):
  fonts-noto-core 20201225-2, fonts-liberation 1:2.1.5-3, fonts-dejavu-core 2.37-8, fonts-wqy-zenhei 0.9.45-8
Unpack them (ar x, then tar xf data.tar.xz) and pass the directory that contains usr/.

Only advance widths are kept (no kerning), in font units, for the blocks map labels use. CJK ideographs are all
one width in these fonts; the script checks that and stores the exceptions.

Usage: python3 -I scripts/font_metrics.py <unpacked-root> > src/fonts/metrics.json   (needs fontTools)
"""
import json
import os
import sys
from collections import Counter

from fontTools.ttLib import TTCollection, TTFont

FONTS = {
    "Noto Sans": ("truetype/noto/NotoSans-Regular.ttf", "truetype/noto/NotoSans-Bold.ttf"),
    "Noto Serif": ("truetype/noto/NotoSerif-Regular.ttf", "truetype/noto/NotoSerif-Bold.ttf"),
    "Liberation Sans": ("truetype/liberation/LiberationSans-Regular.ttf", "truetype/liberation/LiberationSans-Bold.ttf"),
    "Liberation Serif": ("truetype/liberation/LiberationSerif-Regular.ttf", "truetype/liberation/LiberationSerif-Bold.ttf"),
    "DejaVu Sans": ("truetype/dejavu/DejaVuSans.ttf", "truetype/dejavu/DejaVuSans-Bold.ttf"),
    "DejaVu Serif": ("truetype/dejavu/DejaVuSerif.ttf", "truetype/dejavu/DejaVuSerif-Bold.ttf"),
    "WenQuanYi Zen Hei": ("truetype/wqy/wqy-zenhei.ttc#0", None),
}
# Blocks kept glyph by glyph: Latin, Greek, Cyrillic, punctuation, symbols, CJK punctuation, kana, full-width forms.
BLOCKS = [(0x20, 0x24F), (0x370, 0x4FF), (0x2000, 0x22FF), (0x2460, 0x24FF), (0x3000, 0x30FF), (0xFF00, 0xFFEF)]
# Blocks stored as one common width plus exceptions: CJK ideographs.
IDEO = [(0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x323AF)]


def load(root, rel):
    path, _, idx = rel.partition("#")
    full = os.path.join(root, "usr/share/fonts", path)
    return TTCollection(full).fonts[int(idx)] if idx else TTFont(full)


def bbox(font, ch):
    gs = font.getGlyphSet()
    cmap = font.getBestCmap()
    if ord(ch) not in cmap:
        return None
    from fontTools.pens.boundsPen import BoundsPen
    pen = BoundsPen(gs)
    gs[cmap[ord(ch)]].draw(pen)
    return pen.bounds


def face(font):
    upm = font["head"].unitsPerEm
    cmap = font.getBestCmap()
    hmtx = font["hmtx"]
    adv = lambda cp: hmtx[cmap[cp]][0]  # noqa: E731
    runs = []
    for lo, hi in BLOCKS:
        cps = [cp for cp in range(lo, hi + 1) if cp in cmap]
        for cp in cps:
            if runs and runs[-1][0] + len(runs[-1][1]) == cp:
                runs[-1][1].append(adv(cp))
            else:
                runs.append([cp, [adv(cp)]])
    ideo = [cp for lo, hi in IDEO for cp in range(lo, hi + 1) if cp in cmap]
    common = Counter(adv(cp) for cp in ideo).most_common(1)[0][0] if ideo else None
    ranges = []
    for lo, hi in IDEO:
        cps = [cp for cp in range(lo, hi + 1) if cp in cmap]
        if cps:
            ranges.append([cps[0], cps[-1], len(cps)])
    exceptions = {str(cp): adv(cp) for cp in ideo if adv(cp) != common}
    H = bbox(font, "H")
    p = bbox(font, "p")
    zh = bbox(font, "中")
    return {
        "unitsPerEm": upm,
        "capHeight": H[3] if H else None,
        "descent": -p[1] if p else None,
        "ideoTop": zh[3] if zh else None,
        "ideoBottom": -zh[1] if zh else None,
        "runs": runs,
        "ideo": {"advance": common, "ranges": ranges, "exceptions": exceptions} if ideo else None,
    }


def main():
    root = sys.argv[1]
    out = {"_source": "Debian trixie: fonts-noto-core 20201225-2, fonts-liberation 2.1.5-3, fonts-dejavu-core 2.37-8, "
                      "fonts-wqy-zenhei 0.9.45-8. Advance widths in font units; generated by scripts/font_metrics.py.",
           "fonts": {}}
    for name, (regular, bold) in FONTS.items():
        out["fonts"][name] = {"regular": face(load(root, regular)), "bold": face(load(root, bold)) if bold else None}
    json.dump(out, sys.stdout, ensure_ascii=False, separators=(",", ":"))
    sys.stdout.write("\n")


if __name__ == "__main__":
    main()
